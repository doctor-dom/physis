function parseCsvLine(line) {
  const result = [];
  let current = "";
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') {
      inQuotes = !inQuotes;
    } else if (ch === "," && !inQuotes) {
      result.push(current.trim());
      current = "";
    } else {
      current += ch;
    }
  }
  result.push(current.trim());
  return result;
}

function readCsv(filePath) {
  const text = fs.readFileSync(filePath, "utf8");
  return text.split(/\r?\n/).filter((l) => l.trim().length > 0);
}

function parseOriginalRwt(filePath) {
  const lines = readCsv(filePath);
  const headerIdx = lines.findIndex((l) => l.startsWith("age_years,"));
  if (headerIdx === -1) throw new Error(`No header in ${filePath}`);
  const rows = [];
  for (let i = headerIdx + 1; i < lines.length; i++) {
    const cols = parseCsvLine(lines[i]);
    if (cols.length < 7) continue;
    const ageYears = parseFloat(cols[0]);
    const ageMonths = parseFloat(cols[1]);
    if (Number.isNaN(ageYears)) continue;
    rows.push({
      ageYears: ageYears + ageMonths / 12,
      coefficients: {
        beta0: parseFloat(cols[6]),
        betaHeight: parseFloat(cols[2]),
        betaWeight: parseFloat(cols[3]),
        betaMph: parseFloat(cols[4]),
        betaBoneAge: parseFloat(cols[5]),
      },
    });
  }
  return rows;
}

