function copyCahCharts() {
  fs.mkdirSync(cahDest, { recursive: true });
  let maxMtime = 0;
  let copied = 0;

  for (const name of CAH_CHART_FILES) {
    const candidates = [
      path.join(excelDir, name),
      path.join(cahAltSrc, name),
    ];
    const srcPath = candidates.find((p) => fs.existsSync(p));
    if (!srcPath) continue;
    const stat = fs.statSync(srcPath);
    fs.copyFileSync(srcPath, path.join(cahDest, name));
    if (stat.mtimeMs > maxMtime) maxMtime = stat.mtimeMs;
    copied++;
  }

  writeCahChartAssets(maxMtime, copied);
  return copied;
}

function writeCahChartAssets(maxMtime, copiedCount) {
  const bust = maxMtime || Date.now();
  const out = path.join(dataDir, "cah", "chartAssets.ts");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  const content = `/** Auto-generated by import-clinical-data.mjs — run npm run import:data */

export const CAH_CACHE_BUST = "${bust}";

/** Public URLs for CAH nomogram PNGs (${copiedCount}/${CAH_CHART_FILES.length} copied). */
export const CAH_CHART_URLS = {
  cah2003: "/cah/CAH-2003.png?v=${bust}",
  cah2018: "/cah/CAH-2018.png?v=${bust}",
  cah2018Israel: "/cah/CAH-2018-Israel.png?v=${bust}",
} as const;
`;
  fs.writeFileSync(out, content);
  console.log(`Wrote ${out} (${copiedCount} CAH chart PNGs)`);
}

