function parseCah2003Thresholds(filePath) {
  const lines = readCsv(filePath);
  const rows = [];
  for (const line of lines) {
    if (line.startsWith("#") || !line.trim()) continue;
    const cols = parseCsvLine(line);
    if (cols.length < 6) continue;
    const bwMinG = parseFloat(cols[0]);
    if (Number.isNaN(bwMinG)) continue;
    rows.push({
      bwMinG,
      bwMaxG: parseFloat(cols[1]),
      ageMinDays: parseFloat(cols[2]),
      ageMaxDays: parseFloat(cols[3]),
      normalMaxNmol: parseFloat(cols[4]),
      elevatedMaxNmol: parseFloat(cols[5]),
    });
  }
  if (rows.length === 0) {
    throw new Error(`No CAH-2003 threshold rows in ${filePath}`);
  }
  return rows;
}

function parseOptionalCsvNumber(value) {
  if (value == null || String(value).trim() === "") return null;
  const n = parseFloat(value);
  return Number.isNaN(n) ? null : n;
}

function parseCah2018Thresholds(filePath) {
  const lines = readCsv(filePath);
  const rows = [];
  for (const line of lines) {
    if (line.startsWith("#") || !line.trim()) continue;
    const cols = parseCsvLine(line);
    if (cols.length < 6) continue;
    const stratification = cols[0].trim();
    if (
      stratification !== "bw_only" &&
      stratification !== "ga_only" &&
      stratification !== "bw_and_ga"
    ) {
      continue;
    }
    const bwMinG = parseFloat(cols[1]);
    if (Number.isNaN(bwMinG)) continue;

    const percentiles = [
      { percentile: 99.0, cutoffNmol: parseOptionalCsvNumber(cols[5]) },
      { percentile: 99.9, cutoffNmol: parseOptionalCsvNumber(cols[6]) },
      { percentile: 99.95, cutoffNmol: parseOptionalCsvNumber(cols[7]) },
      { percentile: 99.97, cutoffNmol: parseOptionalCsvNumber(cols[8]) },
      { percentile: 99.99, cutoffNmol: parseOptionalCsvNumber(cols[9]) },
    ].filter((tier) => tier.cutoffNmol != null);
    if (percentiles.length === 0) continue;

    rows.push({
      stratification,
      bwMinG,
      bwMaxG: parseFloat(cols[2]),
      gaMinWeeks: parseFloat(cols[3]),
      gaMaxWeeks: parseFloat(cols[4]),
      percentiles,
      rowLabel: cols.length >= 11 ? cols[10].trim() : undefined,
    });
  }
  if (rows.length === 0) {
    throw new Error(`No CAH-2018 threshold rows in ${filePath}`);
  }
  return rows;
}

function parseCahIsraelThresholds(filePath) {
  const lines = readCsv(filePath);
  const rows = [];
  for (const line of lines) {
    if (line.startsWith("#") || !line.trim()) continue;
    const cols = parseCsvLine(line);
    if (cols.length < 10) continue;
    const bwMinG = parseFloat(cols[0]);
    if (Number.isNaN(bwMinG)) continue;
    rows.push({
      bwMinG,
      bwMaxG: parseFloat(cols[1]),
      gaMinWeeks: parseFloat(cols[2]),
      gaMaxWeeks: parseFloat(cols[3]),
      matchesUnknownGa: cols[4].trim().toLowerCase() === "true",
      repeatRequestCutoffNmol: parseFloat(cols[5]),
      firstSampleReferralCutoffNmol: parseOptionalCsvNumber(cols[6]),
      repeatNormalRule: cols[7].trim(),
      repeatNormalAbsoluteNmol: parseOptionalCsvNumber(cols[8]),
      reductionMinPct: parseOptionalCsvNumber(cols[9]),
      rowLabel: cols.length >= 11 ? cols[10].trim() : undefined,
    });
  }
  if (rows.length === 0) {
    throw new Error(`No CAH-2018-Israel threshold rows in ${filePath}`);
  }
  return rows;
}

