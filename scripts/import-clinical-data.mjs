function slugifyFormulaId(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function parseEnteralGirFormulas(filePath) {
  const lines = readCsv(filePath);
  if (lines.length < 2) throw new Error(`No data rows in ${filePath}`);

  const header = parseCsvLine(lines[0]);
  if (header[0] !== "Formula") {
    throw new Error(`Expected "Formula" column in ${filePath}`);
  }

  const kcalColumns = [];
  for (let i = 1; i < header.length; i++) {
    const col = header[i];
    if (col === "Refs") break;
    const match = col.match(/CHO at (\d+(?:\.\d+)?) kcal\/oz/i);
    if (match) {
      kcalColumns.push({ kcalPerOz: parseFloat(match[1]), colIndex: i });
    }
  }

  if (kcalColumns.length === 0) {
    throw new Error(`No CHO kcal/oz columns found in ${filePath}`);
  }

  const rows = [];
  for (let i = 1; i < lines.length; i++) {
    const cols = parseCsvLine(lines[i]);
    const label = cols[0]?.trim();
    if (!label) continue;

    const choMgPerMl = {};
    for (const { kcalPerOz, colIndex } of kcalColumns) {
      const value = parseFloat(cols[colIndex]);
      if (!Number.isNaN(value)) {
        choMgPerMl[kcalPerOz] = value;
      }
    }

    const refsCol = header.indexOf("Refs");
    const refs =
      refsCol >= 0 && cols[refsCol]?.trim() ? cols[refsCol].trim() : undefined;

    rows.push({
      id: slugifyFormulaId(label),
      label,
      choMgPerMl,
      ...(refs ? { refs } : {}),
    });
  }

  return {
    formulas: rows,
    kcalPerOzOptions: kcalColumns.map((c) => c.kcalPerOz).sort((a, b) => a - b),
  };
}

